/// Pragmatic centre of each row (keys have different widths).
const MIDLOC: [f32; 8] = [7.5, 7.5, 7.5, 6.5, 6.5, 6.5, 4.5, 7.5];

/// Returns -1.0 (far left) .. 1.0 (far right); 0.0 for unknown keys.
pub fn find_key_loc(code: u16) -> f32 {
    if code == 0 {
        return 0.0;
    }
    for (row, keys) in KEYLOC.iter().enumerate() {
        if let Some(idx) = keys.iter().rposition(|&k| k == code) {
            let col = (idx + 1) as f32;
            let len = keys.len() as f32;
            return (col - MIDLOC[row]) / (len - MIDLOC[row]);
        }
    }
    0.0
}